// Ghostty setup (SPEC §9.3): acmd's own agent-command.ghostty with the two
// native keybinds (Ghostty keybinds can't run commands, §7.3), included
// from the user's config with an optional include, so a missing file
// never breaks Ghostty (M0 G11).

// GhosttyConfName is acmd's own Ghostty config file.
const GhosttyConfName = "agent-command.ghostty"

// GhosttyConfigDir is Ghostty's XDG config directory.
func GhosttyConfigDir(home string, getenv func(string) string) string {
	if x := getenv("XDG_CONFIG_HOME"); x != "" {
		return filepath.Join(x, "ghostty")
	}
	return filepath.Join(home, ".config", "ghostty")
}

// GhosttyBind is one keybind acmd adds.
type GhosttyBind struct {
	Key, Action, What string
	// Chain are actions run after Action (Ghostty ≥ 1.3 `chain=`).
	Chain []string
}

// GhosttyBinds are acmd's Ghostty keybinds for the configured keys, the
// same combos as in Kitty. Toggle and focus are native Ghostty actions;
// the others focus the sidebar and send it the action's private key code
// (keymap.Code), since Ghostty keybinds can't run programs.
func GhosttyBinds(k Keys) []GhosttyBind {
	out := []GhosttyBind{
		{Key: k.Toggle, Action: "toggle_split_zoom", What: "toggle"},
		{Key: k.Focus, Action: "goto_split:left", What: "focus"},
	}
	viaSidebar := func(key, action string) {
		code, _ := keymap.Code(action)
		out = append(out, GhosttyBind{Key: key, Action: "goto_split:left", What: action, Chain: []string{"csi:" + keymap.CSI(code)}})
	}
	viaSidebar(k.New, "new")
	viaSidebar(k.Attention, "next-attention")
	viaSidebar(k.Picker, "pick")
	viaSidebar(k.Cheatsheet, "keys")
	viaSidebar(k.Editor, "open")
	viaSidebar(k.Adopt, "adopt")
	viaSidebar(k.Term, "term")
	if k.GotoPrefix != "" {
		for n := 1; n <= 9; n++ {
			viaSidebar(fmt.Sprintf("%s+%d", k.GotoPrefix, n), fmt.Sprintf("go %d", n))
		}
	}
	var kept []GhosttyBind
	for _, b := range out {
		if b.Key != "" && !strings.HasPrefix(b.Key, "+") {
			kept = append(kept, b)
		}
	}
	return kept
}

var ghosttyMods = map[string]string{
	"cmd": "super", "command": "super", "super": "super", "ctrl": "ctrl", "control": "ctrl",
	"alt": "alt", "opt": "alt", "option": "alt", "shift": "shift",
}

// NormalizeGhosttyKey makes triggers comparable: Ghostty prints cmd as
// super (G11); modifiers sorted, prefixes like global: dropped.
func NormalizeGhosttyKey(trigger string) string {
	t := strings.ToLower(strings.TrimSpace(trigger))
	for {
		i := strings.Index(t, ":")
		if i < 0 || strings.Contains(t[:i], "+") {
			break
		}
		t = t[i+1:] // global:, all:, unconsumed:, performable:
	}
	parts := strings.Split(t, "+")
	var mods []string
	key := ""
	for _, p := range parts {
		if m, ok := ghosttyMods[p]; ok {
			mods = append(mods, m)
		} else {
			key = p
		}
	}
	sort.Strings(mods)
	return strings.Join(append(mods, key), "+")
}

// ParseGhosttyKeybinds reads `keybind = trigger=action` lines (a user
// config, or `ghostty +list-keybinds` output) into trigger → line.
func ParseGhosttyKeybinds(text string) map[string]string {
	out := map[string]string{}
	for _, l := range strings.Split(text, "\n") {
		l = strings.TrimSpace(l)
		if l == "" || strings.HasPrefix(l, "#") {
			continue
		}
		v := l
		if rest, ok := strings.CutPrefix(l, "keybind"); ok {
			rest = strings.TrimSpace(rest)
			after, ok := strings.CutPrefix(rest, "=")
			if !ok {
				continue
			}
			v = strings.TrimSpace(after)
		}
		trigger, action, ok := strings.Cut(v, "=")
		if !ok {
			trigger, action, ok = strings.Cut(v, " ")
		}
		if !ok || strings.TrimSpace(action) == "" || strings.Contains(trigger, " ") {
			continue
		}
		out[NormalizeGhosttyKey(trigger)] = l
	}
	return out
}

// GhosttyConflicts returns, per acmd bind clashing with a user keybind or
// a Ghostty default, the reason to skip it.
func GhosttyConflicts(binds []GhosttyBind, user, defaults map[string]string) map[string]string {
	out := map[string]string{}
	for _, b := range binds {
		k := NormalizeGhosttyKey(b.Key)
		if line, ok := user[k]; ok {
			out[k] = "conflicts with your `" + line + "`"
		} else if line, ok := defaults[k]; ok {
			out[k] = "conflicts with Ghostty's default " + line
		}
	}
	return out
}

// RenderGhosttyConf renders agent-command.ghostty.
func RenderGhosttyConf(binds []GhosttyBind, skip map[string]string) string {
	var b strings.Builder
	b.WriteString("# Managed by acmd (agent-command). Regenerated by `acmd init --ghostty`; removed by `acmd uninstall`.\n")
	b.WriteString("# Ghostty keybinds can't run programs: acmd's shortcuts focus the view's sidebar and send it a private key (chain=csi:…u).\n")
	for _, kb := range binds {
		if reason, ok := skip[NormalizeGhosttyKey(kb.Key)]; ok {
			fmt.Fprintf(&b, "# skipped %s (%s): %s\n", kb.Key, kb.What, reason)
			continue
		}
		fmt.Fprintf(&b, "keybind = %s=%s\n", kb.Key, kb.Action)
		for _, c := range kb.Chain {
			fmt.Fprintf(&b, "keybind = chain=%s\n", c)
		}
	}
	return b.String()
}

// ghosttyConf is config.ghostty if it exists, else config.
func (in Input) ghosttyConf() string {
	if _, err := in.Read(filepath.Join(in.GhosttyDir, "config.ghostty")); err == nil {
		return filepath.Join(in.GhosttyDir, "config.ghostty")
	}
	return filepath.Join(in.GhosttyDir, "config")
}
func (in Input) ghosttyOwned() string { return filepath.Join(in.GhosttyDir, GhosttyConfName) }

func planGhosttyInit(p *Plan, in Input) error {
	conf := in.ghosttyConf()
	old, exists, err := readOptional(in.Read, conf)
	if err != nil {
		return err
	}
	body := "config-file = ?" + GhosttyConfName
	text, _ := EnsureBlock(string(old), body)
	c := Change{Path: conf, Exists: exists, Old: old, New: []byte(text), Mode: 0o644,
		Summary: "add a managed block that includes " + GhosttyConfName + " (optional include; your lines are unchanged)",
		Detail:  []string{BlockBegin, body, BlockEnd}}
	if !exists {
		c.Summary = "create it with just the optional include for " + GhosttyConfName
	}
	p.Changes = append(p.Changes, c)

	binds := GhosttyBinds(in.Keys)
	skip := GhosttyConflicts(binds, ParseGhosttyKeybinds(string(old)), in.GhosttyKeys)
	rendered := RenderGhosttyConf(binds, skip)
	ownedOld, ownedExists, err := readOptional(in.Read, in.ghosttyOwned())
	if err != nil {
		return err
	}
	p.Changes = append(p.Changes, Change{Path: in.ghosttyOwned(), Exists: ownedExists, Old: ownedOld, New: []byte(rendered), Mode: 0o644,
		Summary: "acmd's own file: " + keybinds(len(binds)-len(skip)),
		Detail:  strings.Split(strings.TrimRight(rendered, "\n"), "\n")})
	for _, b := range binds {
		if reason, ok := skip[NormalizeGhosttyKey(b.Key)]; ok {
			p.Notes = append(p.Notes, fmt.Sprintf("Ghostty: skipped %s (%s): %s", b.Key, b.What, reason))
		}
	}
	if in.GhosttyKeys == nil {
		p.Notes = append(p.Notes, "Ghostty: couldn't read Ghostty's default keybinds, so only your own were checked for conflicts")
	}
	p.After = append(p.After, "Ghostty reloads its config now if it's running (or at its next start). The first time acmd controls Ghostty, macOS asks to allow it: choose Allow.")
	return nil
}

func planGhosttyUninstall(p *Plan, in Input) error {
	old, exists, err := readOptional(in.Read, in.ghosttyConf())
	if err != nil {
		return err
	}
	if exists {
		text, found := RemoveBlock(string(old))
		c := Change{Path: in.ghosttyConf(), Exists: true, Old: old, New: []byte(text),
			Summary: "remove acmd's include block (your lines are unchanged)"}
		if !found {
			c.Summary = "no acmd block"
		}
		p.Changes = append(p.Changes, c)
	}
	owned, ownedExists, err := readOptional(in.Read, in.ghosttyOwned())
	if err != nil {
		return err
	}
	if ownedExists {
		p.Changes = append(p.Changes, Change{Path: in.ghosttyOwned(), Exists: true, Old: owned, Remove: true,
			Summary: "acmd's Ghostty keybinds"})
	}
	return nil
}

func keybinds(n int) string {
	if n == 1 {
		return "1 keybind"
	}
	return fmt.Sprintf("%d keybinds", n)
}
