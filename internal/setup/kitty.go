// Managed block markers for line-based configs (SPEC §9).
const (
	BlockBegin = "# >>> acmd (managed block: do not edit; run `acmd uninstall` to remove) >>>"
	BlockEnd   = "# <<< acmd <<<"
)

// KittyConfName is acmd's own Kitty config file, next to kitty.conf.
const KittyConfName = "agent-command.conf"

// EnsureBlock puts body in a managed block at the end of text, replacing an
// existing block. It's idempotent.
func EnsureBlock(text, body string) (string, bool) {
	block := BlockBegin + "\n" + strings.TrimRight(body, "\n") + "\n" + BlockEnd + "\n"
	base, _ := RemoveBlock(text)
	var out string
	switch {
	case base == "":
		out = block
	case strings.HasSuffix(base, "\n"):
		out = base + "\n" + block
	default:
		out = base + "\n\n" + block
	}
	return out, out != text
}

// RemoveBlock removes the managed block and the blank line EnsureBlock put
// before it. For text that ended with a newline (or was empty),
// RemoveBlock(EnsureBlock(text)) == text.
func RemoveBlock(text string) (string, bool) {
	i := strings.Index(text, BlockBegin)
	if i < 0 {
		return text, false
	}
	j := strings.Index(text[i:], BlockEnd)
	if j < 0 {
		return text, false // unterminated: leave it for the user
	}
	end := i + j + len(BlockEnd)
	if end < len(text) && text[end] == '\n' {
		end++
	}
	before, after := text[:i], text[end:]
	if after == "" && strings.HasSuffix(before, "\n\n") {
		before = before[:len(before)-1]
	}
	return before + after, true
}

// KittyBind is one global shortcut acmd adds to Kitty (SPEC §8.3, §9.2).
type KittyBind struct {
	Key    string // e.g. "cmd+shift+n"
	Action string // e.g. "new", for reporting
	Launch string // launch arguments after "launch"
}

// KittyBinds returns acmd's Kitty shortcuts for the given keys. Background
// launches get --allow-remote-control and @active-kitty-window-id, since a
// background launch otherwise has no socket, window id or cwd (M0 K7/K8).
func KittyBinds(acmd string, k Keys) []KittyBind {
	q := shellQuote(acmd)
	bg := func(args string) string {
		return "--type=background --allow-remote-control " + q + " " + args + " --kitty-window @active-kitty-window-id"
	}
	binds := []KittyBind{
		{k.Toggle, "toggle", bg("toggle")},
		{k.New, "new", bg("new")},
		{k.Focus, "focus", bg("focus")},
		{k.Attention, "next-attention", bg("next-attention")},
		{k.Picker, "pick", "--type=overlay " + q + " pick"},
		{k.Cheatsheet, "keys", "--type=overlay " + q + " keys --interactive"},
		{k.Editor, "open", bg("open")},
	}
	for n := 1; n <= 9; n++ {
		binds = append(binds, KittyBind{fmt.Sprintf("%s+%d", k.GotoPrefix, n), fmt.Sprintf("go %d", n), bg(fmt.Sprintf("go %d", n))})
	}
	var out []KittyBind
	for _, b := range binds {
		if b.Key != "" {
			out = append(out, b)
		}
	}
	return out
}

// Keys are the configurable global shortcuts (SPEC §10 [keys]).
type Keys struct {
	Toggle, New, Focus, Attention, Picker, Cheatsheet, Editor, GotoPrefix string
}

// DefaultKeys are SPEC §8.3's defaults.
var DefaultKeys = Keys{
	Toggle: "cmd+shift+b", New: "cmd+shift+n", Focus: "cmd+shift+s", Attention: "cmd+shift+a",
	Picker: "cmd+shift+l", Cheatsheet: "cmd+shift+k", Editor: "cmd+shift+e", GotoPrefix: "ctrl+cmd",
}

// RenderKittyConf renders agent-command.conf. Binds in skip (normalized key
// → reason) are left out and listed as comments. Kitty doesn't allow
// inline comments, so every comment is on its own line.
func RenderKittyConf(binds []KittyBind, skip map[string]string) string {
	var b strings.Builder
	b.WriteString("# Managed by acmd (agent-command). Regenerated by `acmd init`; removed by `acmd uninstall`.\n")
	b.WriteString("allow_remote_control socket-only\n")
	b.WriteString("listen_on unix:kitty-acmd-{kitty_pid}\n")
	for _, kb := range binds {
		if reason, ok := skip[NormalizeKey(kb.Key, "")]; ok {
			fmt.Fprintf(&b, "# skipped %s (%s): %s\n", kb.Key, kb.Action, reason)
			continue
		}
		fmt.Fprintf(&b, "map %s launch %s\n", kb.Key, kb.Launch)
	}
	return b.String()
}

// modifier aliases → canonical names, in canonical order.
var modOrder = []string{"ctrl", "alt", "shift", "super"}

var modAlias = map[string]string{
	"ctrl": "ctrl", "control": "ctrl", "c": "ctrl", "^": "ctrl",
	"alt": "alt", "opt": "alt", "option": "alt", "⌥": "alt",
	"shift": "shift", "⇧": "shift",
	"super": "super", "cmd": "super", "command": "super", "⌘": "super",
}

var keyAlias = map[string]string{"/": "slash", ",": "comma", ".": "period", "=": "equal", "-": "minus", "?": "slash"}

// NormalizeKey canonicalizes a Kitty key spec ("cmd+shift+N", "kitty_mod+n")
// so different spellings compare equal. kittyMod is the user's kitty_mod
// (default ctrl+shift).
func NormalizeKey(spec, kittyMod string) string {
	if kittyMod == "" {
		kittyMod = "ctrl+shift"
	}
	parts := strings.Split(strings.ToLower(strings.TrimSpace(spec)), "+")
	mods := map[string]bool{}
	key := ""
	for i, p := range parts {
		if p == "" && i == len(parts)-1 { // "ctrl++" means the plus key
			key = "plus"
			continue
		}
		if p == "kitty_mod" {
			for _, m := range strings.Split(kittyMod, "+") {
				if c, ok := modAlias[m]; ok {
					mods[c] = true
				}
			}
			continue
		}
		if c, ok := modAlias[p]; ok && i < len(parts)-1 {
			mods[c] = true
			continue
		}
		if a, ok := keyAlias[p]; ok {
			p = a
		}
		key = p
	}
	var out []string
	for _, m := range modOrder {
		if mods[m] {
			out = append(out, m)
		}
	}
	return strings.Join(append(out, key), "+")
}

// KittyConfig is what acmd learns from the user's Kitty config files.
type KittyConfig struct {
	Maps     map[string]string // normalized key → the user's map line
	Settings map[string]string // last value of selected settings (allow_remote_control, listen_on, kitty_mod)
	Files    []string          // files read (kitty.conf and includes)
}

// ParseKittyConfig reads kitty.conf and its includes (relative to the
// config dir; globs allowed), skipping acmd's own file. read returns a
// file's content (os.ReadFile in production).
func ParseKittyConfig(confPath string, read func(string) ([]byte, error)) (KittyConfig, error) {
	kc := KittyConfig{Maps: map[string]string{}, Settings: map[string]string{}}
	seen := map[string]bool{}
	var rawMaps []string
	var walk func(path string, depth int) error
	walk = func(path string, depth int) error {
		if depth > 8 || seen[path] || filepath.Base(path) == KittyConfName {
			return nil
		}
		seen[path] = true
		b, err := read(path)
		if err != nil {
			if depth == 0 {
				return err
			}
			return nil // missing include: Kitty ignores it too
		}
		kc.Files = append(kc.Files, path)
		for _, line := range strings.Split(string(b), "\n") {
			line = strings.TrimSpace(line)
			if line == "" || strings.HasPrefix(line, "#") {
				continue
			}
			fields := strings.Fields(line)
			switch fields[0] {
			case "map":
				if len(fields) >= 2 {
					rawMaps = append(rawMaps, line)
				}
			case "include", "globinclude":
				if len(fields) < 2 {
					continue
				}
				target := strings.Join(fields[1:], " ")
				if !filepath.IsAbs(target) {
					target = filepath.Join(filepath.Dir(confPath), target)
				}
				if fields[0] == "globinclude" || strings.ContainsAny(target, "*?[") {
					matches, _ := filepath.Glob(target)
					sort.Strings(matches)
					for _, m := range matches {
						if err := walk(m, depth+1); err != nil {
							return err
						}
					}
					continue
				}
				if err := walk(target, depth+1); err != nil {
					return err
				}
			case "allow_remote_control", "listen_on", "kitty_mod":
				kc.Settings[fields[0]] = strings.Join(fields[1:], " ")
			}
		}
		return nil
	}
	if err := walk(confPath, 0); err != nil {
		return kc, err
	}
	// kitty_mod can be set anywhere; resolve maps after reading everything.
	for _, line := range rawMaps {
		fields := strings.Fields(line)
		key := fields[1]
		if strings.HasPrefix(key, "--") && len(fields) >= 3 { // map --when-focus-on ... key action
			continue
		}
		kc.Maps[NormalizeKey(key, kc.Settings["kitty_mod"])] = line
	}
	return kc, nil
}

// Conflicts returns, for each of acmd's binds that clashes with a user map
// or a Kitty default, the reason to skip it (keyed by normalized key).
// defaults maps normalized keys to Kitty's default action.
func Conflicts(binds []KittyBind, user KittyConfig, defaults map[string]string) map[string]string {
	out := map[string]string{}
	for _, b := range binds {
		k := NormalizeKey(b.Key, "")
		if line, ok := user.Maps[k]; ok {
			out[k] = "conflicts with your `" + line + "`"
			continue
		}
		if action, ok := defaults[k]; ok {
			out[k] = "conflicts with Kitty's default " + action
		}
	}
	return out
}

// ParseKittyDefaults parses the output of KittyDefaultsScript: one
// "<normalized key>\t<action>" per line.
func ParseKittyDefaults(out []byte) map[string]string {
	defaults := map[string]string{}
	for _, line := range strings.Split(string(out), "\n") {
		key, action, ok := strings.Cut(strings.TrimSpace(line), "\t")
		if ok && key != "" {
			defaults[NormalizeKey(key, "")] = action
		}
	}
	return defaults
}

// KittyDefaultsScript prints Kitty's default single-key shortcuts as
// "<mods+key>\t<action>" lines; run with `kitty +runpy`.
const KittyDefaultsScript = `
from kitty.options.types import defaults
from kitty.fast_data_types import GLFW_MOD_CONTROL as C, GLFW_MOD_ALT as A, GLFW_MOD_SHIFT as S, GLFW_MOD_SUPER as P
for kd in defaults.map:
    t = kd.trigger
    mods, key = getattr(t, 'mods', None), getattr(t, 'key', None)
    if mods is None or key is None:
        continue
    names = [n for bit, n in ((C, 'ctrl'), (A, 'alt'), (S, 'shift'), (P, 'super')) if mods & bit]
    k = chr(key) if 32 < key < 0xE000 else str(key)
    print('+'.join(names + [k]) + '\t' + str(kd.definition))
`
